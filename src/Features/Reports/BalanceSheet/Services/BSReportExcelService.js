const buildBSSheet = (wb) => {
  const ws = wb.addWorksheet('BS', {
    views: [{ state: 'frozen', xSplit: 0, ySplit: 7 }],
    pageSetup: { paperSize: 9, orientation: 'landscape', fitToPage: true, fitToWidth: 1 },
  })
  //  A=col1(sr), B=col2(sr sub), C=col3(particulars), D=col4(note), E=col5(CY), F=col6(PY)
  ws.columns = [
    { width: 4 }, { width: 4 }, { width: 42 },
    { width: 8 }, { width: 20 }, { width: 20 },
  ]
  const TC = 6
  let r = addCompanyHeader(ws, TC, 'Balance Sheet as on 31st March 2024')

  // ── Column Headers ──────────────────────────────────────────────────────────
  safeMerge(ws, r, 1, 3)
  ws.getCell(r, 1).value = 'Particulars'
  applyStyle(ws.getCell(r, 1), { bold: true, size: 11, bg: C.navyBlue, color: C.white, hAlign: 'center', border: 'medium', borderColor: C.black })
  ws.getCell(r, 4).value = 'Note\nNo'
  applyStyle(ws.getCell(r, 4), { bold: true, size: 11, bg: C.navyBlue, color: C.white, hAlign: 'center', wrapText: true, border: 'medium', borderColor: C.black })
  ws.getCell(r, 5).value = '31st March 2024'
  applyStyle(ws.getCell(r, 5), { bold: true, size: 11, bg: C.navyBlue, color: C.white, hAlign: 'center', border: 'medium', borderColor: C.black })
  ws.getCell(r, 6).value = '31st March 2023'
  applyStyle(ws.getCell(r, 6), { bold: true, size: 11, bg: C.navyBlue, color: C.white, hAlign: 'center', border: 'medium', borderColor: C.black })
  ws.getRow(r).height = 26; r++

  // ── Helper: section banner (full width) ─────────────────────────────────────
  const sectionBanner = (label) => {
    mergeCenter(ws, r, 1, TC, label, {
      bold: true, size: 11, bg: C.lightBlue, color: C.navyBlue, border: 'thin',
    })
    ws.getRow(r).height = 18; r++
  }

  // ── Helper: sub-group heading (cols 2-6 merged, col 1 = number) ─────────────
  const groupHeading = (srNo, label) => {
    ws.getCell(r, 1).value = srNo
    applyStyle(ws.getCell(r, 1), { bold: true, size: 10, bg: C.lightGold, border: 'thin' })
    safeMerge(ws, r, 2, TC)
    ws.getCell(r, 2).value = label
    applyStyle(ws.getCell(r, 2), { bold: true, underline: true, size: 10, bg: C.lightGold, border: 'thin' })
    ws.getRow(r).height = 17; r++
  }

  // ── Helper: data row (cols 1-3 merged for label, col4=note, col5=CY, col6=PY) ─
  const dataRow = (label, note, cy, py, opts = {}) => {
    const { bold = false, isTotal = false, indent = '' } = opts
    const bg = isTotal ? C.lightGold : null
    safeMerge(ws, r, 1, 3)
    ws.getCell(r, 1).value = indent + label
    applyStyle(ws.getCell(r, 1), { bold: bold || isTotal, size: 10, bg, border: 'thin', wrapText: true })
    ws.getCell(r, 4).value = note || ''
    applyStyle(ws.getCell(r, 4), { hAlign: 'center', size: 10, bg, border: 'thin' })
    ;[cy, py].forEach((v, i) => {
      const cell = ws.getCell(r, i + 5)
      const n = fmt(v)
      if (n !== null) { cell.value = n; cell.numFmt = NUM_FMT }
      else { cell.value = '-' }
      applyStyle(cell, { bold: bold || isTotal, hAlign: 'right', size: 10, bg, border: 'thin' })
    })
    ws.getRow(r).height = 17; r++
  }

  // ── Helper: total / grand-total banner row (full dark header style) ──────────
  const totalBanner = (label, cy, py) => {
    safeMerge(ws, r, 1, 4)
    ws.getCell(r, 1).value = label
    applyStyle(ws.getCell(r, 1), { bold: true, size: 11, bg: C.navyBlue, color: C.white, border: 'medium', borderColor: C.black })
    ;[cy, py].forEach((v, i) => {
      const cell = ws.getCell(r, i + 5)
      const n = fmt(v)
      if (n !== null) { cell.value = n; cell.numFmt = NUM_FMT }
      else { cell.value = '-' }
      applyStyle(cell, { bold: true, size: 11, hAlign: 'right', bg: C.navyBlue, color: C.white, border: 'medium', borderColor: C.black })
    })
    ws.getRow(r).height = 20; r++
  }

  const spacer = () => { ws.getRow(r).height = 6; r++ }

  // ════════════════════════════════════════════════
  // I. EQUITY AND LIABILITIES
  // ════════════════════════════════════════════════
  sectionBanner('I.  EQUITY AND LIABILITIES')
  const eq = BS_DATA.equityAndLiabilities

  // 1. Shareholders' Funds
  groupHeading('1', "Shareholder's Funds")
  dataRow('(a) Share Capital', eq.shareholdersFunds.shareCapital.note, eq.shareholdersFunds.shareCapital.cy, eq.shareholdersFunds.shareCapital.py, { indent: '    ' })
  dataRow('(b) Reserves and Surplus', eq.shareholdersFunds.reservesAndSurplus.note, eq.shareholdersFunds.reservesAndSurplus.cy, eq.shareholdersFunds.reservesAndSurplus.py, { indent: '    ' })
  dataRow('', null, eq.shareholdersFunds.totalShareholdersFunds.cy, eq.shareholdersFunds.totalShareholdersFunds.py, { isTotal: true })

  // 2. Non-Current Liabilities
  groupHeading('2', 'Non-Current Liabilities')
  const ncl = eq.nonCurrentLiabilities
  dataRow('(a) Long-term borrowings', ncl.longTermBorrowings.note, ncl.longTermBorrowings.cy, ncl.longTermBorrowings.py, { indent: '    ' })
  dataRow('(b) Deferred tax liabilities', null, ncl.deferredTaxLiabilities.cy, ncl.deferredTaxLiabilities.py, { indent: '    ' })
  dataRow('(c) Other Long term liabilities', null, ncl.otherLongTermLiabilities.cy, ncl.otherLongTermLiabilities.py, { indent: '    ' })
  dataRow('(d) Long term provisions', null, ncl.longTermProvisions.cy, ncl.longTermProvisions.py, { indent: '    ' })
  dataRow('', null, ncl.totalNonCurrentLiabilities.cy, ncl.totalNonCurrentLiabilities.py, { isTotal: true })

  // 3. Current Liabilities
  groupHeading('3', 'Current Liabilities')
  const cl = eq.currentLiabilities
  dataRow('(a) Short-term borrowings', cl.shortTermBorrowings.note, cl.shortTermBorrowings.cy, cl.shortTermBorrowings.py, { indent: '    ' })
  dataRow('(b) Trade payables', cl.tradePayablesMSME.note || '', null, null, { indent: '    ' })
  dataRow('     Total outstanding dues of micro enterprises and small enterprises', null, cl.tradePayablesMSME.cy, cl.tradePayablesMSME.py, { indent: '    ' })
  dataRow('     Total outstanding dues of creditors other than micro enterprises and small enterprises', null, cl.tradePayablesOthers.cy, cl.tradePayablesOthers.py, { indent: '    ' })
  ws.getRow(r - 1).height = 30
  dataRow('(c) Other current liabilities', cl.otherCurrentLiabilities.note, cl.otherCurrentLiabilities.cy, cl.otherCurrentLiabilities.py, { indent: '    ' })
  dataRow('(d) Short-term provisions', cl.shortTermProvisions.note, cl.shortTermProvisions.cy, cl.shortTermProvisions.py, { indent: '    ' })
  dataRow('', null, cl.totalCurrentLiabilities.cy, cl.totalCurrentLiabilities.py, { isTotal: true })

  totalBanner('TOTAL', eq.grandTotal.cy, eq.grandTotal.py)
  spacer()

  // ════════════════════════════════════════════════
  // II. ASSETS
  // ════════════════════════════════════════════════
  sectionBanner('II.  ASSETS')
  const assets = BS_DATA.assets

  // 1. Non-current assets
  groupHeading('1', 'Non-current assets')
  const nca = assets.nonCurrentAssets
  dataRow('(a) Property, Plant and Equipment', nca.ppe.note, nca.ppe.cy, nca.ppe.py, { indent: '    ' })
  dataRow('(b) Intangible assets', nca.intangibleAssets.note, nca.intangibleAssets.cy, nca.intangibleAssets.py, { indent: '    ' })
  dataRow('(c) Non-current investments', null, nca.nonCurrentInvestments.cy, nca.nonCurrentInvestments.py, { indent: '    ' })
  dataRow('(d) Deferred tax assets (Net)', nca.deferredTaxAssetsNet.note, nca.deferredTaxAssetsNet.cy, nca.deferredTaxAssetsNet.py, { indent: '    ' })
  dataRow('(e) Long term loans and advances', null, nca.longTermLoansAndAdvances.cy, nca.longTermLoansAndAdvances.py, { indent: '    ' })

  // 2. Current assets
  groupHeading('2', 'Current assets')
  const ca = assets.currentAssets
  dataRow('(a) Inventories', null, ca.inventories.cy, ca.inventories.py, { indent: '    ' })
  dataRow('(b) Trade receivables', ca.tradeReceivables.note, ca.tradeReceivables.cy, ca.tradeReceivables.py, { indent: '    ' })
  dataRow('(c) Cash and cash equivalents', ca.cashAndCashEquivalents.note, ca.cashAndCashEquivalents.cy, ca.cashAndCashEquivalents.py, { indent: '    ' })
  dataRow('(d) Short-term loans and advances', ca.shortTermLoansAndAdvances.note, ca.shortTermLoansAndAdvances.cy, ca.shortTermLoansAndAdvances.py, { indent: '    ' })
  dataRow('(e) Other current assets', ca.otherCurrentAssets.note, ca.otherCurrentAssets.cy, ca.otherCurrentAssets.py, { indent: '    ' })

  totalBanner('Total...', assets.grandTotal.cy, assets.grandTotal.py)
  spacer()

  // Notes to Accounts
  safeMerge(ws, r, 1, 3)
  ws.getCell(r, 1).value = 'Notes to Accounts'
  applyStyle(ws.getCell(r, 1), { bold: true, size: 10, border: 'thin' })
  ws.getCell(r, 4).value = '1'
  applyStyle(ws.getCell(r, 4), { hAlign: 'center', size: 10, border: 'thin' })
  ws.getCell(r, 5).value = '-'; ws.getCell(r, 6).value = '-'
  applyStyle(ws.getCell(r, 5), { border: 'thin' }); applyStyle(ws.getCell(r, 6), { border: 'thin' })
  ws.getRow(r).height = 17; r++

  spacer(); r++
  addFooter(ws, r, TC)
}

