// ─── STYLE HELPERS ─────────────────────────────────────────────────────────────

const applyStyle = (cell, opts = {}) => {
  const {
    bold = false, italic = false, size = 10, color = C.black,
    bg = null, hAlign = 'left', vAlign = 'middle', wrapText = false,
    numFmt = null, border = 'thin', borderColor = 'FFBFBFBF', underline = false,
  } = opts

  cell.font = { bold, italic, size, color: { argb: color }, name: 'Calibri', underline }
  cell.alignment = { horizontal: hAlign, vertical: vAlign, wrapText }
  if (bg) cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: bg } }
  if (numFmt) cell.numFmt = numFmt
  if (border) {
    const b = { style: border, color: { argb: borderColor } }
    cell.border = { top: b, left: b, bottom: b, right: b }
  }
}

/** Safe merge — wraps in try/catch so already-merged cells won't crash */
const safeMerge = (ws, r, c1, c2) => {
  try {
    if (c1 < c2) ws.mergeCells(r, c1, r, c2)
  } catch (_) { /* already merged — ignore */ }
}

const mergeCenter = (ws, r, c1, c2, value, opts = {}) => {
  safeMerge(ws, r, c1, c2)
  const cell = ws.getCell(r, c1)
  cell.value = value
  applyStyle(cell, opts)
  return cell
}

const fmt = (n) => {
  if (n === 0 || n === null || n === undefined) return null
  return Number(n)
}

