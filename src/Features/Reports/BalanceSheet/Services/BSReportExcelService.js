  row5('Add: Profit (Loss) for the period', pl3.addProfitLoss.cy, pl3.addProfitLoss.py, null, null, { indent: 1 })
  row5('TOTAL...', pl3.total.cy, pl3.total.py, null, null, { isTotal: true })
  blank()

  // ── Simple 2-col note helper ─────────────────────────────────────────────
  const simpleNote = (noteData, extraLabel = null) => {
    noteHdr(noteData.title)
    colHdrs(['Particular', '31st March 2024', '31st March 2023', '', ''])
    if (extraLabel) subHead(extraLabel)
    noteData.items.forEach(item => row5(item.name, item.cy, item.py, null, null, { indent: 1 }))
    row5('TOTAL...', noteData.total.cy, noteData.total.py, null, null, { isTotal: true })
    blank()
  }

  simpleNote(S.note4_longTermBorrowings, 'Unsecured Loans')
  simpleNote(S.note5_shortTermBorrowings, S.note5_shortTermBorrowings.label)

  // ── Note 6: Trade Payables ────────────────────────────────────────────────
  noteHdr(S.note6_tradePayables.title)
  mergeCenter(ws, r, 1, TC, S.note6_tradePayables.msmeNote, {
    size: 9, italic: true, wrapText: true, border: 'thin',
  })
  ws.getRow(r).height = 32; r++

  ;[S.note6_tradePayables.currentYear, S.note6_tradePayables.previousYear].forEach(yr => {
    subHead(yr.label)
    colHdrs(['Particulars', 'Less than\n6 Months', '6 Mo to\n1 Year', '1 to 2\nYears', 'Total'])
    yr.rows.forEach(row => {
      row5(row.category, row.lt6, row.m6to1y, row.m1to2y, row.total)
    })
    blank()
  })

  simpleNote(S.note7_otherCurrentLiabilities)
  simpleNote(S.note8_shortTermProvisions)
  simpleNote(S.note10_deferredTaxAssets)

  // ── Note 11: Trade Receivables ────────────────────────────────────────────
  noteHdr(S.note11_tradeReceivables.title)
  colHdrs(['Trade Receivables', '31st March 2024 ₹', '31st March 2023 ₹', '', ''])
