  subHead('Terms/rights attached to equity shares')
  mergeCenter(ws, r, 1, TC, S.note2_shareCapital.termsRights, {
    size: 9, italic: true, wrapText: true, border: 'thin',
  })
  ws.getRow(r).height = 52; r++
  blank()

  subHead('Equity Shares held (More than 5%)')
  colHdrs(['Name of Shareholder', '31st Mar 2024\nNo. of Shares', '31st Mar 2024\n% Holding', '31st Mar 2023\nNo. of Shares', '31st Mar 2023\n% Holding'])
