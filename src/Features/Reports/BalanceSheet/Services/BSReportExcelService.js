export const generateBSReportExcel = async () => {
  try {
    console.log('=== BS Report Excel Generation Started ===')

    const workbook = new ExcelJS.Workbook()
    workbook.creator = 'iSmart Accounts System'
    workbook.created = new Date()
    workbook.modified = new Date()

    buildBSSheet(workbook)
    buildBSScheduleSheet(workbook)
    buildPLSheet(workbook)
    buildPLScheduleSheet(workbook)
    buildFANoteSheet(workbook)

    const buffer = await workbook.xlsx.writeBuffer()
    const timestamp = new Date().toISOString().slice(0, 10)
    const filename = `Balance_Sheet_${timestamp}.xlsx`
    const blob = new Blob([buffer], {
      type: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
    })
    saveAs(blob, filename)

    console.log('✓ BS Report Excel generated successfully:', filename)
    return { success: true, filename }
  } catch (err) {
    console.error('generateBSReportExcel error:', err)
    throw new Error(`Failed to generate Balance Sheet Excel: ${err.message}`)
  }
}

export default { generateBSReportExcel }
