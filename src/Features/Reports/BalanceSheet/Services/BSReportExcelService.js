  row5('Unsecured, considered good', n11.debtsExceedingSixMonths.unsecuredGood.cy, n11.debtsExceedingSixMonths.unsecuredGood.py, null, null, { indent: 1 })
  row5('Less: Provision for doubtful debts', null, null, null, null, { indent: 1 })
  row5('Subtotal', n11.debtsExceedingSixMonths.subtotal.cy, n11.debtsExceedingSixMonths.subtotal.py, null, null, { bold: true })
