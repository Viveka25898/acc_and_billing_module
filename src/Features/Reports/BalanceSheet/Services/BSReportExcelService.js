  subHead('Issued, Subscribed & Fully Paid Up')
  const isp = S.note2_shareCapital.issuedSubscribedPaidUp
  row5(isp.description, isp.cyNumber, isp.cyAmount, isp.pyNumber, isp.pyAmount, { indent: 1 })
  const t2 = S.note2_shareCapital.total
  row5('TOTAL...', t2.cyNumber, t2.cyAmount, t2.pyNumber, t2.pyAmount, { isTotal: true })
